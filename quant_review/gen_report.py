def embed_image(path, max_width=None, max_height=None):
    if max_width is None:
        max_width = AVAIL_W
    if max_height is None:
        max_height = PAGE_H * 0.34
    im = PILImage.open(path)
    ow, oh = im.size
    ratio = min(max_width / ow, max_height / oh, 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)

def chart(story, fname, caption, max_h=None):
    story.append(Spacer(1, 14))
    img = embed_image(os.path.join(CHARTS, fname), max_height=max_h or PAGE_H * 0.32)
    story.append(KeepTogether([img, Paragraph(caption, S["caption"])]))
    story.append(Spacer(1, 10))

def make_table(header, rows, ratios, caption=None, left_cols=(0,), font_size=9.0):
    th = ParagraphStyle("THx", parent=S["th"], fontSize=font_size)
    td = ParagraphStyle("TDx", parent=S["td"], fontSize=font_size)
    tdl = ParagraphStyle("TDLx", parent=S["tdl"], fontSize=font_size)
    data = [[Paragraph(f"<b>{c}</b>", th) for c in header]]
    for row in rows:
        cells = []
        for j, c in enumerate(row):
            cells.append(Paragraph(str(c), tdl if j in left_cols else td))
        data.append(cells)
    widths = [r * AVAIL_W for r in ratios]
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i), colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12), t]
    if caption:
        out += [Paragraph(caption, S["caption"])]
    out += [Spacer(1, 10)]
    return out

def callout(story, stats):
    """stats: list of (value, label) tuples -> row of stat boxes."""
    n = len(stats)
    cells = []
    for v, lab in stats:
        inner = Table([[Paragraph(f"<b>{v}</b>", S["stat"])], [Paragraph(lab, S["statlab"])]],
                      colWidths=[(AVAIL_W - 12 * (n - 1)) / n - 8])
        inner.setStyle(TableStyle([
            ("TOPPADDING", (0, 0), (-1, 0), 7), ("BOTTOMPADDING", (0, 1), (-1, 1), 7),
            ("TOPPADDING", (0, 1), (-1, 1), 1), ("BOTTOMPADDING", (0, 0), (-1, 0), 1),
            ("LEFTPADDING", (0, 0), (-1, -1), 2), ("RIGHTPADDING", (0, 0), (-1, -1), 2),
        ]))
        cells.append(inner)
    row = Table([cells], colWidths=[AVAIL_W / n] * n, hAlign="CENTER")
    row.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 0.8, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.8, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(Spacer(1, 10))
    story.append(KeepTogether(row))
    story.append(Spacer(1, 12))

# ── doc template with TOC + header/footer ───────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))

